/** El enlace de una ayuda, usando la web de tu comunidad cuando la gestiona ella */
export function enlaceDe(ayuda, ccaa) {
  if (!ayuda.enlace.ccaa) return ayuda.enlace;
  const c = COMUNIDADES.find((x) => x.id === ccaa);
  return c ? { texto: `Web de ${c.nombre}`, url: c.url } : { texto: 'La web de tu comunidad', url: null };
}
